import type { PlaybookState } from '@/lib/soar-types';
import type { FortiSOARDeploymentProfile } from '@/lib/fortisoar-types';

function QAMatrixReport({
  playbook,
  deploymentProfile,
}: {
  playbook: PlaybookState;
  deploymentProfile: FortiSOARDeploymentProfile;
}) {
  const templateId = playbook.templateId || playbook.generatorType || '';
  const qaEntry = SOAR_QA_MATRIX.find((e) => e.templateId === templateId);

  if (!qaEntry) {
    return (
      <Card className="p-6">
        <div className="flex items-center gap-2 mb-3">
          <ShieldCheck className="w-5 h-5 text-muted-foreground" />
          <h3 className="font-semibold">QA Matrix</h3>
        </div>
        <p className="text-sm text-muted-foreground">
          QA matrix validation is available for predefined templates only. Custom templates do not have expected step sets.
        </p>
      </Card>
    );
  }

  const qaRow: QAReportRow = useMemo(() => {
    try {
      const collection = generateFortiSOARWorkflowCollection(playbook, deploymentProfile);
      const workflow = collection.data[0]?.workflows[0];
      const stepNames = workflow?.steps.map((s) => s.name) ?? [];
      return runQAReportRow(templateId, stepNames);
    } catch {
      return runQAReportRow(templateId, []);
    }
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [templateId, playbook, deploymentProfile]);

  const passed = qaRow.status === 'pass';
  const allConnectors = qaRow.requiredConnectors;

  return (
    <Card className="p-6">
      <div className="flex items-center justify-between mb-4 flex-wrap gap-2">
        <div className="flex items-center gap-2">
          <ShieldCheck className={`w-5 h-5 ${passed ? 'text-green-400' : 'text-red-400'}`} />
          <h3 className="font-semibold">QA Matrix Report</h3>
        </div>
        <span className={`px-2.5 py-0.5 text-xs font-medium rounded border ${
          passed
            ? 'bg-green-900/20 border-green-800/30 text-green-400'
            : 'bg-red-900/20 border-red-800/30 text-red-400'
        }`}>
          {passed ? 'PASS' : 'FAIL'}
        </span>
      </div>

      <div className="overflow-x-auto rounded-lg border border-border mb-4">
        <table className="w-full text-xs">
          <thead>
            <tr className="border-b border-border bg-muted/40">
              <th className="text-left px-3 py-2 font-medium text-muted-foreground">Template</th>
              <th className="text-left px-3 py-2 font-medium text-muted-foreground">Generator</th>
              <th className="text-left px-3 py-2 font-medium text-muted-foreground">Expected Steps</th>
              <th className="text-left px-3 py-2 font-medium text-muted-foreground">Required Connectors</th>
              <th className="text-left px-3 py-2 font-medium text-muted-foreground">Guardrails</th>
              <th className="text-left px-3 py-2 font-medium text-muted-foreground">Status</th>
            </tr>
          </thead>
          <tbody>
            <tr className="border-b border-border/50">
              <td className="px-3 py-2.5 font-medium">{qaRow.templateName}</td>
              <td className="px-3 py-2.5 font-mono text-muted-foreground">{qaRow.generatorFunction}</td>
              <td className="px-3 py-2.5 text-muted-foreground">
                {qaRow.presentStepCount}/{qaRow.expectedStepCount} present
              </td>
              <td className="px-3 py-2.5">
                <div className="flex flex-wrap gap-1">
                  {allConnectors.map((c) => {
                    const cfg = deploymentProfile?.connectors[c];
                    const isConfigured = cfg && cfg.isConfigured;
                    return (
                      <span key={c} className={`px-1.5 py-0.5 rounded text-[10px] border ${
                        isConfigured
                          ? 'bg-green-900/20 border-green-800/30 text-green-400'
                          : 'bg-gray-800/40 border-gray-700/30 text-gray-400'
                      }`}>
                        {c}
                      </span>
                    );
                  })}
                </div>
              </td>
              <td className="px-3 py-2.5 text-muted-foreground">{qaRow.guardrailCount} defined</td>
              <td className="px-3 py-2.5">
                {passed ? (
                  <span className="flex items-center gap-1 text-green-400">
                    <CheckCircle className="w-3 h-3" /> Pass
                  </span>
                ) : (
                  <span className="flex items-center gap-1 text-red-400">
                    <XCircle className="w-3 h-3" /> Fail
                  </span>
                )}
              </td>
            </tr>
          </tbody>
        </table>
      </div>

      {qaRow.missingMustContain.length > 0 && (
        <div className="mb-3 p-3 bg-red-900/10 border border-red-900/30 rounded-lg">
          <p className="text-xs font-medium text-red-400 mb-1.5">Missing required steps (mustContain):</p>
          <div className="flex flex-wrap gap-1.5">
            {qaRow.missingMustContain.map((s) => (
              <span key={s} className="px-2 py-0.5 text-xs font-mono bg-red-900/20 border border-red-800/30 text-red-300 rounded">
                {s}
              </span>
            ))}
          </div>
        </div>
      )}

      {qaRow.forbiddenPresent.length > 0 && (
        <div className="mb-3 p-3 bg-red-900/10 border border-red-900/30 rounded-lg">
          <p className="text-xs font-medium text-red-400 mb-1.5">Forbidden steps found (mustNotContain):</p>
          <div className="flex flex-wrap gap-1.5">
            {qaRow.forbiddenPresent.map((s) => (
              <span key={s} className="px-2 py-0.5 text-xs font-mono bg-red-900/20 border border-red-800/30 text-red-300 rounded">
                {s}
              </span>
            ))}
          </div>
        </div>
      )}

      <details className="text-xs">
        <summary className="cursor-pointer text-muted-foreground hover:text-foreground transition-colors py-1 select-none">
          View {qaEntry.guardrails.length} defined guardrails
        </summary>
        <ul className="mt-2 space-y-1 pl-2 border-l border-border">
          {qaEntry.guardrails.map((g, i) => (
            <li key={i} className="text-muted-foreground">{g}</li>
          ))}
        </ul>
      </details>

      {passed && (
        <p className="mt-3 text-xs text-green-400">
          All required steps present. No forbidden steps detected. Template uses a real generator (not generic workflow).
        </p>
      )}
    </Card>
  );
}

